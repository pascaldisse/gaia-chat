// Markdown Formatter
class MarkdownFormatter extends BaseFormatter {
  constructor() {
    super();
    this.mimeType = 'text/markdown';
    this.extension = 'md';
  }

  async format(scanResults, options = {}) {
    const total = this.getTotalVulnerabilities(scanResults.summary);
    
    let markdown = `# CVE Security Audit Report\n\n`;
    markdown += `**Scanned on:** ${this.formatDate(scanResults.scannedAt)}\n\n`;
    
    // Summary
    markdown += `## Executive Summary\n\n`;
    markdown += `| Severity | Count |\n`;
    markdown += `|----------|-------|\n`;
    markdown += `| ${this.getSeverityEmoji('critical')} Critical | ${scanResults.summary.critical} |\n`;
    markdown += `| ${this.getSeverityEmoji('high')} High | ${scanResults.summary.high} |\n`;
    markdown += `| ${this.getSeverityEmoji('medium')} Medium | ${scanResults.summary.medium} |\n`;
    markdown += `| ${this.getSeverityEmoji('low')} Low | ${scanResults.summary.low} |\n`;
    markdown += `| **Total** | **${total}** |\n\n`;
    
    if (total === 0) {
      markdown += `### ✅ No vulnerabilities found!\n\n`;
      markdown += `Your dependencies are secure and up to date.\n\n`;
    } else {
      markdown += `## Vulnerability Details\n\n`;
      
      for (const item of scanResults.vulnerabilities) {
        markdown += this.renderDependencySection(item);
      }
    }
    
    markdown += `---\n\n`;
    markdown += `*Generated by Gaia CVE Scanner*\n`;
    
    return markdown;
  }

  renderDependencySection(item) {
    const { dependency, vulnerabilities, remediation } = item;
    
    let section = `### 📦 ${dependency.name} @ ${dependency.version} (${dependency.ecosystem})\n\n`;
    
    for (const vuln of vulnerabilities) {
      section += this.renderVulnerability(vuln);
    }
    
    if (remediation.actions.length > 0) {
      section += `#### 💡 Remediation\n\n`;
      for (const action of remediation.actions) {
        section += `\`\`\`bash\n${action.command}\n\`\`\`\n\n`;
      }
      
      if (remediation.breakingChanges) {
        section += `> ⚠️ **Warning:** This update includes breaking changes\n\n`;
      }
    }
    
    return section;
  }

  renderVulnerability(vuln) {
    const severity = this.getSeverityLevel(vuln.cvss);
    const emoji = this.getSeverityEmoji(severity);
    
    let content = `#### ${emoji} ${vuln.cve || vuln.id} - ${severity.toUpperCase()} (CVSS: ${vuln.cvss.toFixed(1)})\n\n`;
    content += `${vuln.summary}\n\n`;
    
    if (vuln.fixedVersions.length > 0) {
      content += `**Fixed in:** ${vuln.fixedVersions.join(', ')}\n\n`;
    }
    
    return content;
  }

  getTotalVulnerabilities(summary) {
    return summary.critical + summary.high + summary.medium + summary.low;
  }

  getSeverityLevel(cvss) {
    if (cvss >= 9.0) return 'critical';
    if (cvss >= 7.0) return 'high';
    if (cvss >= 4.0) return 'medium';
    return 'low';
  }
}

// CSV Formatter
class CsvFormatter extends BaseFormatter {
  constructor() {
    super();
    this.mimeType = 'text/csv';
    this.extension = 'csv';
  }

  async format(scanResults, options = {}) {
    const rows = [];
    
    // Header
    rows.push([
      'Dependency',
      'Version',
      'Ecosystem',
      'Vulnerability ID',
      'CVE',
      'Severity',
      'CVSS Score',
      'Summary',
      'Fixed Versions',
      'Remediation Command'
    ]);
    
    // Data rows
    for (const item of scanResults.vulnerabilities) {
      const { dependency, vulnerabilities, remediation } = item;
      
      for (const vuln of vulnerabilities) {
        const severity = this.getSeverityLevel(vuln.cvss);
        const remediationCmd = remediation.actions[0]?.command || '';
        
        rows.push([
          dependency.name,
          dependency.version,
          dependency.ecosystem,
          vuln.id,
          vuln.cve || '',
          severity,
          vuln.cvss.toFixed(1),
          this.escapeCSV(vuln.summary),
          vuln.fixedVersions.join('; '),
          this.escapeCSV(remediationCmd)
        ]);
      }
    }
    
    return rows.map(row => row.join(',')).join('\n');
  }

  escapeCSV(value) {
    if (!value) return '';
    
    // Escape quotes and wrap in quotes if contains comma, newline, or quotes
    if (value.includes(',') || value.includes('\n') || value.includes('"')) {
      return `"${value.replace(/"/g, '""')}"`;
    }
    
    return value;
  }

  getSeverityLevel(cvss) {
    if (cvss >= 9.0) return 'critical';
    if (cvss >= 7.0) return 'high';
    if (cvss >= 4.0) return 'medium';
    return 'low';
  }
}

// SARIF Formatter (for GitHub/VS Code integration)
class SarifFormatter extends BaseFormatter {
  constructor() {
    super();
    this.mimeType = 'application/sarif+json';
    this.extension = 'sarif';
  }

  async format(scanResults, options = {}) {
    const sarif = {
      version: '2.1.0',
      runs: [{
        tool: {
          driver: {
            name: 'Gaia CVE Scanner',
            version: '1.0.0',
            informationUri: 'https://github.com/gaia/cve-scanner',
            rules: this.generateRules(scanResults)
          }
        },
        results: this.generateResults(scanResults)
      }]
    };
    
    return JSON.stringify(sarif, null, 2);
  }

  generateRules(scanResults) {
    const rules = [];
    const seenRules = new Set();
    
    for (const item of scanResults.vulnerabilities) {
      for (const vuln of item.vulnerabilities) {
        const ruleId = vuln.cve || vuln.id;
        
        if (!seenRules.has(ruleId)) {
          seenRules.add(ruleId);
          
          rules.push({
            id: ruleId,
            name: ruleId,
            shortDescription: {
              text: vuln.summary
            },
            fullDescription: {
              text: vuln.details || vuln.summary
            },
            defaultConfiguration: {
              level: this.getSarifLevel(vuln.cvss)
            },
            properties: {
              'security-severity': vuln.cvss.toString()
            }
          });
        }
      }
    }
    
    return rules;
  }

  generateResults(scanResults) {
    const results = [];
    
    for (const item of scanResults.vulnerabilities) {
      const { dependency, vulnerabilities } = item;
      
      for (const vuln of vulnerabilities) {
        results.push({
          ruleId: vuln.cve || vuln.id,
          level: this.getSarifLevel(vuln.cvss),
          message: {
            text: `${dependency.name}@${dependency.version} has vulnerability: ${vuln.summary}`
          },
          locations: [{
            physicalLocation: {
              artifactLocation: {
                uri: this.getDependencyFile(dependency.ecosystem)
              }
            }
          }]
        });
      }
    }
    
    return results;
  }

  getSarifLevel(cvss) {
    if (cvss >= 9.0) return 'error';
    if (cvss >= 7.0) return 'error';
    if (cvss >= 4.0) return 'warning';
    return 'note';
  }

  getDependencyFile(ecosystem) {
    const files = {
      npm: 'package.json',
      pip: 'requirements.txt',
      pub: 'pubspec.yaml'
    };
    return files[ecosystem] || 'unknown';
  }
}

export default ReportGenerator;
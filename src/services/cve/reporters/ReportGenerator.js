/**
 * Report Generator
 * Generates vulnerability reports in multiple formats
 */

class ReportGenerator {
  constructor() {
    this.formatters = {
      json: new JsonFormatter(),
      html: new HtmlFormatter(),
      markdown: new MarkdownFormatter(),
      csv: new CsvFormatter(),
      sarif: new SarifFormatter() // GitHub/VS Code compatible format
    };
  }

  async generateReport(scanResults, format = 'json', options = {}) {
    const formatter = this.formatters[format];
    if (!formatter) {
      throw new Error(`Unsupported report format: ${format}`);
    }

    const report = await formatter.format(scanResults, options);
    
    return {
      content: report,
      mimeType: formatter.mimeType,
      extension: formatter.extension,
      filename: this.generateFilename(format)
    };
  }

  generateFilename(format) {
    const timestamp = new Date().toISOString().replace(/[:.]/g, '-');
    return `cve-audit-report-${timestamp}.${this.formatters[format].extension}`;
  }

  async generateMultipleFormats(scanResults, formats = ['json', 'html']) {
    const reports = {};
    
    for (const format of formats) {
      try {
        reports[format] = await this.generateReport(scanResults, format);
      } catch (error) {
        console.error(`Failed to generate ${format} report:`, error);
      }
    }
    
    return reports;
  }
}

// Base formatter class
class BaseFormatter {
  constructor() {
    this.mimeType = 'text/plain';
    this.extension = 'txt';
  }

  async format(scanResults, options) {
    throw new Error('format() must be implemented by subclass');
  }

  getSeverityEmoji(severity) {
    const emojis = {
      critical: '🔴',
      high: '🟠',
      medium: '🟡',
      low: '🔵'
    };
    return emojis[severity] || '⚪';
  }

  formatDate(date) {
    return new Date(date).toLocaleString();
  }
}

// JSON Formatter
class JsonFormatter extends BaseFormatter {
  constructor() {
    super();
    this.mimeType = 'application/json';
    this.extension = 'json';
  }

  async format(scanResults, options = {}) {
    const report = {
      reportVersion: '1.0.0',
      scanDate: scanResults.scannedAt,
      summary: scanResults.summary,
      totalVulnerabilities: this.getTotalVulnerabilities(scanResults.summary),
      vulnerabilities: scanResults.vulnerabilities.map(item => ({
        dependency: item.dependency,
        vulnerabilities: item.vulnerabilities.map(vuln => ({
          id: vuln.id,
          cve: vuln.cve,
          severity: this.getSeverityLevel(vuln.cvss),
          cvss: vuln.cvss,
          summary: vuln.summary,
          details: vuln.details,
          published: vuln.published,
          references: vuln.references,
          fixedVersions: vuln.fixedVersions
        })),
        remediation: item.remediation
      }))
    };

    if (options.pretty) {
      return JSON.stringify(report, null, 2);
    }
    
    return JSON.stringify(report);
  }

  getTotalVulnerabilities(summary) {
    return summary.critical + summary.high + summary.medium + summary.low;
  }

  getSeverityLevel(cvss) {
    if (cvss >= 9.0) return 'critical';
    if (cvss >= 7.0) return 'high';
    if (cvss >= 4.0) return 'medium';
    return 'low';
  }
}

